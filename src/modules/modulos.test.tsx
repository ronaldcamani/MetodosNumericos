/** Abre el panel y elige una herramienta del selector (si la página ofrece varias). */
async function herramienta(u: ReturnType<typeof userEvent.setup>, id: string, nombre: string) {
  await abrirPanel(u)
  const selector = screen.queryByLabelText('Herramienta')
  if (selector) await u.selectOptions(selector, id)
  return screen.getByRole('region', { name: nombre })
}

